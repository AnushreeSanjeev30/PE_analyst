"""
financial_models.py

Typed data models used by the Financial Agent.

These models ensure that every financial analysis
is returned in a structured, consistent format.
"""

from dataclasses import dataclass, field
from enum import StrEnum

# ==========================================================
# ENUMS
# ==========================================================

class FinancialHealth(StrEnum):
    EXCELLENT = "Excellent"
    GOOD = "Good"
    AVERAGE = "Average"
    WEAK = "Weak"
    DISTRESSED = "Distressed"


class Trend(StrEnum):
    IMPROVING = "Improving"
    STABLE = "Stable"
    DECLINING = "Declining"


# ==========================================================
# INDIVIDUAL FINDING
# ==========================================================

@dataclass(slots=True)
class FinancialFinding:
    """
    Represents one financial observation.
    """

    title: str
    description: str
    severity: str = "INFO"


# ==========================================================
# METRIC SCORE
# ==========================================================

@dataclass(slots=True)
class MetricScore:
    """
    Represents one calculated financial metric.
    """

    name: str
    value: float
    benchmark: float | None = None
    unit: str = ""


# ==========================================================
# FINANCIAL SUMMARY
# ==========================================================

@dataclass(slots=True)
class FinancialSummary:
    """
    High-level summary generated by the Financial Agent.
    """

    company_name: str

    health: FinancialHealth

    trend: Trend

    confidence: float

    executive_summary: str


# ==========================================================
# STRENGTHS
# ==========================================================

@dataclass(slots=True)
class FinancialStrength:
    title: str
    explanation: str


# ==========================================================
# WEAKNESSES
# ==========================================================

@dataclass(slots=True)
class FinancialWeakness:
    title: str
    explanation: str


# ==========================================================
# RECOMMENDATION
# ==========================================================

@dataclass(slots=True)
class FinancialRecommendation:
    recommendation: str
    reasoning: str


# ==========================================================
# COMPLETE REPORT
# ==========================================================

@dataclass(slots=True)
class FinancialReport:
    """
    Complete output produced by the Financial Agent.
    """

    summary: FinancialSummary

    findings: list[FinancialFinding] = field(default_factory=list)

    metrics: list[MetricScore] = field(default_factory=list)

    strengths: list[FinancialStrength] = field(default_factory=list)

    weaknesses: list[FinancialWeakness] = field(default_factory=list)

    recommendation: FinancialRecommendation | None = None